#!/usr/bin/env bash
# GamesTracker Vault — install or update with Docker, in one command:
#
#   curl -fsSL https://raw.githubusercontent.com/TTiagoSousa/GamesTracker-Vault/main/deploy/docker/install.sh | bash
#
# Creates a folder (default ./gamestracker-vault) with docker-compose.yml and a .env with
# random secrets, then starts the app and its database. Running it again in the same
# place updates: it downloads the newest compose file and image, and keeps the .env.
#
# Optional variables:
#   INSTALL_DIR     where to put the files (default: ./gamestracker-vault)
#   PORT            port on this machine (default: 8080)
#   APP_URL         the address people open (default: http://<this machine's IP>:PORT)
#   ADMIN_USERNAME  first account (default: admin); its password is generated
#   TZ              time zone (default: this machine's)
#   VERSION         image tag (default: latest)
#   REF             git branch or tag the compose file comes from (default: main)
set -euo pipefail

REPO="TTiagoSousa/GamesTracker-Vault"
REF="${REF:-main}"
RAW="https://raw.githubusercontent.com/${REPO}/${REF}/deploy/docker"
INSTALL_DIR="${INSTALL_DIR:-$PWD/gamestracker-vault}"

GREEN=$'\033[1;32m'; CYAN=$'\033[1;36m'; YELLOW=$'\033[1;33m'; RED=$'\033[1;31m'; BOLD=$'\033[1m'; RESET=$'\033[0m'
msg()  { printf '%s ➜%s %s\n' "$CYAN" "$RESET" "$*"; }
ok()   { printf '%s ✓%s %s\n' "$GREEN" "$RESET" "$*"; }
warn() { printf '%s !%s %s\n' "$YELLOW" "$RESET" "$*" >&2; }
die()  { printf '%s ✗%s %s\n' "$RED" "$RESET" "$*" >&2; exit 1; }

# --- requirements -----------------------------------------------------------------------

command -v docker >/dev/null || die "Docker is not installed. Install it first: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "The Docker Compose plugin is missing (docker compose). See https://docs.docker.com/compose/install/"
docker info >/dev/null 2>&1 || die "Cannot talk to Docker. Start it, or run this as a user in the docker group (or with sudo)."
command -v curl >/dev/null || die "curl is required."

secret_hex() { # secret_hex <bytes>
  if command -v openssl >/dev/null; then openssl rand -hex "$1"
  else od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; fi
}
secret_b64() { # secret_b64 <bytes>
  if command -v openssl >/dev/null; then openssl rand -base64 "$1" | tr -d '\n'
  else head -c "$1" /dev/urandom | base64 | tr -d '\n'; fi
}
host_ip() { hostname -I 2>/dev/null | awk '{print $1}' || true; }
host_tz() { timedatectl show -p Timezone --value 2>/dev/null || cat /etc/timezone 2>/dev/null || echo Etc/UTC; }

# --- files ------------------------------------------------------------------------------

mkdir -p "$INSTALL_DIR"
cd "$INSTALL_DIR"
msg "Folder: $INSTALL_DIR"

msg "Downloading docker-compose.yml ($REF)…"
curl -fsSL "$RAW/docker-compose.yml" -o docker-compose.yml.new
mv docker-compose.yml.new docker-compose.yml
curl -fsSL "$RAW/.env.example" -o .env.example

FIRST_INSTALL=""
if [ -f .env ]; then
  ok "Keeping the existing .env (secrets and settings)"
else
  FIRST_INSTALL=1
  PORT="${PORT:-8080}"
  IP="$(host_ip)"
  APP_URL="${APP_URL:-http://${IP:-localhost}:${PORT}}"
  ADMIN_USERNAME="${ADMIN_USERNAME:-admin}"
  ADMIN_PASSWORD="$(secret_hex 9)"
  msg "Writing .env with new secrets…"
  umask 077
  cat > .env <<EOF
# GamesTracker Vault — generated by install.sh on $(date '+%Y-%m-%d %H:%M').
# The variables are explained in .env.example. After editing: docker compose up -d

DB_PASSWORD=$(secret_hex 24)
JWT_SECRET=$(secret_hex 48)
# ⚠ Never change it: it encrypts the keys stored in the database.
TOKEN_ENCRYPTION_KEY=$(secret_b64 32)

ADMIN_USERNAME=${ADMIN_USERNAME}
ADMIN_PASSWORD=${ADMIN_PASSWORD}

PORT=${PORT}
APP_URL=${APP_URL%/}
TRUST_PROXY=loopback, uniquelocal
TZ=${TZ:-$(host_tz)}
VERSION=${VERSION:-latest}
EOF
  umask 022
  ok ".env written (only readable by you)"
fi

# --- start ------------------------------------------------------------------------------

msg "Downloading the images…"
docker compose pull --quiet
msg "Starting…"
docker compose up -d --remove-orphans

msg "Waiting for the app to answer…"
for _ in $(seq 1 60); do
  state="$(docker inspect -f '{{.State.Health.Status}}' "$(docker compose ps -q app)" 2>/dev/null || echo starting)"
  [ "$state" = healthy ] && break
  sleep 3
done
[ "${state:-}" = healthy ] || warn "The app is not healthy yet. Logs: cd $INSTALL_DIR && docker compose logs -f app"

# Read back, not sourced: values such as TRUST_PROXY contain spaces.
env_value() { sed -n "s/^$1=//p" .env | tail -1; }
APP_URL="$(env_value APP_URL)"
ADMIN_USERNAME="$(env_value ADMIN_USERNAME)"
ADMIN_PASSWORD="$(env_value ADMIN_PASSWORD)"
cat <<EOF

${GREEN}GamesTracker Vault is running.${RESET}

  Open:     ${BOLD}${APP_URL}${RESET}
EOF
if [ -n "$FIRST_INSTALL" ]; then
  cat <<EOF
  Login:    ${ADMIN_USERNAME} / ${ADMIN_PASSWORD}
            (change the password in Settings → Account)
EOF
fi
cat <<EOF
  Folder:   ${INSTALL_DIR}
  Logs:     docker compose logs -f app
  Update:   run this script again, or: docker compose pull && docker compose up -d

  Next: in the app, Admin → Integrations, add the IGDB keys for the game search.

EOF
